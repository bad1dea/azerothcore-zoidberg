-- IdleBot live state tables for the ops dashboard.
-- idlebot_live_state: written every ~2 s by C++ (one row per active bot).

CREATE TABLE IF NOT EXISTS `idlebot_live_state` (
    `bot_name`                 varchar(64)       NOT NULL,
    `character_guid`           int unsigned      DEFAULT NULL,
    `class_id`                 tinyint unsigned  DEFAULT NULL,
    `race_id`                  tinyint unsigned  DEFAULT NULL,
    `level`                    tinyint unsigned  DEFAULT NULL,
    `map_id`                   smallint unsigned DEFAULT 0,
    `x`                        float             DEFAULT 0,
    `y`                        float             DEFAULT 0,
    `z`                        float             DEFAULT 0,
    `orientation`              float             DEFAULT 0,
    `hp`                       int unsigned      DEFAULT 0,
    `hp_max`                   int unsigned      DEFAULT 0,
    `mana`                     int unsigned      DEFAULT 0,
    `mana_max`                 int unsigned      DEFAULT 0,
    `hp_pct`                   float             DEFAULT 100,
    `mana_pct`                 float             DEFAULT 100,
    `alive`                    tinyint(1)        DEFAULT 1,
    `is_ghost`                 tinyint(1)        DEFAULT 0,
    `in_combat`                tinyint(1)        DEFAULT 0,
    `state`                    varchar(32)       DEFAULT 'idle',
    `guide_id`                 varchar(96)       DEFAULT NULL,
    `soak_run_id`              varchar(32)       DEFAULT NULL,
    `bot_session_id`           varchar(64)       DEFAULT NULL,
    `reset_id`                 int unsigned      NOT NULL DEFAULT 0,
    `step_index`               int unsigned      DEFAULT 0,
    `step_total`               int unsigned      DEFAULT 0,
    `step_name`                varchar(255)      DEFAULT NULL,
    `blocked_reason`           varchar(128)      DEFAULT NULL,
    `blocked_since`            datetime          DEFAULT NULL,
    `last_failure_code`        varchar(64)       DEFAULT NULL,
    `requires_user_action`     tinyint(1)        DEFAULT 0,
    `quest_id`                 int unsigned      DEFAULT NULL,
    `objective_text`           varchar(255)      DEFAULT NULL,
    `target_entry`             int unsigned      DEFAULT NULL,
    `target_name`              varchar(128)      DEFAULT NULL,
    `target_level`             tinyint unsigned  DEFAULT NULL,
    `target_distance`          float             DEFAULT NULL,
    `target_role`              varchar(32)       DEFAULT NULL,
    `death_count_total`        int unsigned      DEFAULT 0,
    `death_count_current_step` int unsigned      DEFAULT 0,
    `money`                    int unsigned      DEFAULT 0,
    `bag_used`                 smallint unsigned DEFAULT 0,
    `bag_total`                smallint unsigned DEFAULT 0,
    `durability_pct`           tinyint unsigned  DEFAULT 100,
    `updated_at`               datetime          DEFAULT NULL,
    PRIMARY KEY (`bot_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
